"""Run and render Horizon's deterministic ablation smoke suite.

For paper-grade evaluation, replace the deterministic adapter results with
model-run JSONL traces and use `benchmarks/horizonbench/score_runs.py`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from benchmarks.horizonbench.run import default_strategies, load_scenarios, run_suite  # noqa: E402


def markdown_table(report: dict) -> str:
    lines = [
        "# HorizonBench Synthetic Ablation Smoke Result",
        "",
        "> This report is generated by a deterministic CI harness. It validates metric and ablation plumbing; it is **not** an empirical LLM result.",
        "",
        "| Variant | Success | Goal retention | Constraint violations/task | Repeated failure | Recovery success | State consistency | Tokens/success | Anchors |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, metric in report["strategies"].items():
        recovery = metric["recovery_success_rate"]
        per_success = metric["tokens_per_successful_task"]
        lines.append(
            "| {} | {:.1%} | {:.1%} | {:.2f} | {:.1%} | {} | {:.1%} | {} | {} |".format(
                name,
                metric["task_success_rate"],
                metric["goal_retention_rate"],
                metric["constraint_violation_rate"],
                metric["repeated_failure_rate"],
                "—" if recovery is None else "{:.1%}".format(recovery),
                metric["state_consistency_rate"],
                "—" if per_success is None else "{:.0f}".format(per_success),
                metric["anchors_injected"],
            )
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    output = ROOT / "results" / "synthetic-ablation"
    report = run_suite(load_scenarios(), default_strategies(include_ablations=True), output)
    output.mkdir(parents=True, exist_ok=True)
    (output / "summary.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (output / "report.md").write_text(markdown_table(report), encoding="utf-8")
    print("Wrote {}".format(output / "report.md"))


if __name__ == "__main__":
    main()
