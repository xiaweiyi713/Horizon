"""Score a frozen HorizonBench cross-model matrix from observed result JSONL.

This command never calls a model.  A provider-specific runner must first write
``<results-dir>/<run_id>.jsonl`` for every manifest generated by
``plan_matrix.py``.  The scorer then checks each trace against its frozen task
set and emits both per-run scores and model/condition summaries across seeds.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from statistics import mean, stdev
from typing import Any, Mapping, Optional, Sequence

try:  # Supports both `python file.py` and module execution.
    from .protocol import (
        ManifestValidationError,
        manifest_summary,
        read_manifest_jsonl,
        validate_comparable_matrix,
        validate_result_task_ids,
    )
    from .score import read_jsonl, score_results
except ImportError:  # pragma: no cover - direct-script compatibility
    from protocol import (  # type: ignore[no-redef]
        ManifestValidationError,
        manifest_summary,
        read_manifest_jsonl,
        validate_comparable_matrix,
        validate_result_task_ids,
    )
    from score import read_jsonl, score_results


def _metric_summary(rows: Sequence[Mapping[str, Any]]) -> dict[str, dict[str, Any]]:
    metric_names = sorted({key for row in rows for key in row})
    summary: dict[str, dict[str, Any]] = {}
    for name in metric_names:
        values = [
            float(row[name])
            for row in rows
            if row.get(name) is not None
            and isinstance(row.get(name), (int, float))
            and not isinstance(row.get(name), bool)
            and math.isfinite(float(row[name]))
        ]
        if not values:
            summary[name] = {"observations": 0, "mean": None, "sample_stddev": None}
            continue
        summary[name] = {
            "observations": len(values),
            "mean": mean(values),
            "sample_stddev": stdev(values) if len(values) > 1 else 0.0,
        }
    return summary


def score_matrix(
    matrix_path: Path,
    results_dir: Path,
    *,
    result_suffix: str = ".jsonl",
) -> dict[str, Any]:
    """Validate and score every row in a reproducible cross-model matrix."""

    if not result_suffix.startswith(".") or len(result_suffix) < 2:
        raise ManifestValidationError("result_suffix must begin with a file extension dot")
    manifests = read_manifest_jsonl(matrix_path)
    validate_comparable_matrix(manifests)
    runs: list[dict[str, Any]] = []
    grouped_metrics: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for manifest in manifests:
        path = results_dir / (manifest.run_id + result_suffix)
        if not path.is_file():
            raise ManifestValidationError(
                "missing result JSONL for run {!r}: {}".format(manifest.run_id, path)
            )
        results = read_jsonl(path)
        validate_result_task_ids(results, manifest)
        metrics = score_results(results).as_dict()
        runs.append(
            {
                "manifest": manifest_summary(manifest),
                "result_path": str(path),
                "metrics": metrics,
            }
        )
        grouped_metrics.setdefault(
            (manifest.model.model_id, manifest.condition.condition_id), []
        ).append(metrics)

    summaries = [
        {
            "model_id": model_id,
            "condition_id": condition_id,
            "run_count": len(metrics),
            "metrics": _metric_summary(metrics),
        }
        for (model_id, condition_id), metrics in sorted(grouped_metrics.items())
    ]
    reference = manifests[0]
    return {
        "protocol": "horizonbench_cross_model_score_v1",
        "matrix_path": str(matrix_path),
        "run_count": len(runs),
        "task_set": reference.task_set.as_dict(),
        "prompt_sha256": reference.prompt.sha256,
        "runtime_revision": reference.runtime_revision,
        "runs": runs,
        "summaries": summaries,
    }


def main(argv: Optional[Sequence[str]] = None) -> None:
    parser = argparse.ArgumentParser(
        description="Score all observed JSONL traces in a frozen HorizonBench model matrix"
    )
    parser.add_argument("--matrix", type=Path, required=True, help="JSONL matrix from plan_matrix.py")
    parser.add_argument("--results-dir", type=Path, required=True, help="directory containing <run_id>.jsonl")
    parser.add_argument("--result-suffix", default=".jsonl", help="result file suffix (default: .jsonl)")
    parser.add_argument("--output", type=Path, default=None, help="optional report JSON destination")
    args = parser.parse_args(argv)
    try:
        report = score_matrix(args.matrix, args.results_dir, result_suffix=args.result_suffix)
    except (ManifestValidationError, ValueError) as error:
        parser.error(str(error))
    encoded = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(encoded, encoding="utf-8")
    print(encoded, end="")


if __name__ == "__main__":
    main()
